// Persisting data the user would actually lose.
//
// Everything in localStorage is not equal. Photos, POI payloads, search results
// and AI destinations are CACHES — throwing them away costs a network request.
// Saved trips, recent searches and preferences are the user's own data, and
// there is no way to get them back.
//
// Until now both were written the same way: `try { setItem } catch {}`. So once
// the ~5 MB origin quota filled up — and it fills with caches, since a single
// city's POI payload now reaches 28 KB — saving a trip failed silently. The app
// still said "Saved!", the user closed it, and the trip was gone.
//
// persist() inverts that priority: if a write fails, disposable caches are
// evicted and the write is retried, so a cache can never crowd out a trip.

// Key prefixes that may be discarded to make room, cheapest-to-refetch first.
// Kept in sync by hand with the modules that own them; a stale entry here only
// means that cache is not offered up, never that anything breaks.
const DISPOSABLE = [
  "vai_ai_dest_",     // aiEngine — regenerated by one API call
  "vai_photo",        // photos.js, any version — re-resolved from Wikipedia
  "vai_dest_q_",      // destinations.js — one Supabase query each
  "vai_osm_city_",    // osmLive.js — one Overpass fetch each
  "vai_pois_",        // poiDb.js — the largest, up to 28 KB per city
  "vai_errors",       // monitor.js — diagnostics, not user data
];

// Drop every key under the given prefixes. Returns how many were removed.
function evict(prefixes) {
  let n = 0;
  try {
    // Collect first: removing while iterating localStorage shifts the indices.
    const doomed = [];
    for (let i = 0; i < localStorage.length; i++) {
      const key = localStorage.key(i);
      if (key && prefixes.some((p) => key.startsWith(p))) doomed.push(key);
    }
    for (const key of doomed) { try { localStorage.removeItem(key); n++; } catch {} }
  } catch { /* storage unavailable entirely — nothing to evict */ }
  return n;
}

// Write a value the user must not lose. Returns true if it landed.
//
// On failure the caches go one group at a time, cheapest first, retrying after
// each — so a full disk costs the user their photo cache rather than their trip.
export function persist(key, value) {
  const write = () => {
    try { localStorage.setItem(key, value); return true; } catch { return false; }
  };
  if (write()) return true;

  for (let i = 0; i < DISPOSABLE.length; i++) {
    // Widen the sacrifice each round rather than dropping everything at once.
    if (evict(DISPOSABLE.slice(0, i + 1)) === 0) continue;
    if (write()) return true;
  }
  return false;
}

// Best-effort write for data that is itself a cache. Never evicts anything —
// a cache failing to save is not a problem worth solving.
export function persistCache(key, value) {
  try { localStorage.setItem(key, value); return true; } catch { return false; }
}
