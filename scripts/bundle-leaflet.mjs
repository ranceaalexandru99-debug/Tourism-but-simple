// Copy Leaflet into the native app as a JS module, so the WebView maps do not
// fetch it from a CDN.
//
// Two reasons. The maps were loading leaflet from unpkg.com, which the privacy
// policy never listed among the services the app contacts — and every service
// it contacts has to be declared. And a map that needs a CDN to be up before it
// can draw anything is a map that fails in a way the user cannot act on: the
// tiles need the network, but the library should not.
//
// Emitted as JSON string literals rather than template literals: Leaflet's
// source contains backticks and ${ sequences, and a template literal would
// either break or, worse, evaluate them.
//
// Run: node scripts/bundle-leaflet.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "node_modules", "leaflet", "dist");
const OUT = path.join(ROOT, "mobile-native", "src", "lib", "leafletAsset.js");

const version = JSON.parse(
  fs.readFileSync(path.join(ROOT, "node_modules", "leaflet", "package.json"), "utf8"),
).version;

const js = fs.readFileSync(path.join(SRC, "leaflet.js"), "utf8");
const css = fs.readFileSync(path.join(SRC, "leaflet.css"), "utf8");

// A closing tag inside the source would end the <script> block it is injected
// into — the same hole a photo caption once opened in the short renderer.
// Leaflet has none today; this makes sure a future version cannot introduce one
// silently.
for (const [name, text, tag] of [["leaflet.js", js, "</script"], ["leaflet.css", css, "</style"]]) {
  if (text.toLowerCase().includes(tag)) {
    throw new Error(`${name} contains ${tag}> — it would escape the block it is embedded in`);
  }
}

const out = `// GENERATED by scripts/bundle-leaflet.mjs — do not edit.
//
// Leaflet ${version}, inlined so the WebView maps need no CDN. See the script
// for why. Re-run it after bumping the leaflet dependency.
//
// The CSS references images/marker-icon.png and images/layers.png. Both maps
// use L.divIcon and no layers control, so neither is ever requested; there is
// nothing to bundle and nothing that reaches the network.

export const LEAFLET_VERSION = ${JSON.stringify(version)};
export const LEAFLET_JS = ${JSON.stringify(js)};
export const LEAFLET_CSS = ${JSON.stringify(css)};
`;

fs.writeFileSync(OUT, out);
console.log(
  `leafletAsset.js scris: Leaflet ${version}, ` +
  `${(js.length / 1024).toFixed(0)} KB JS + ${(css.length / 1024).toFixed(0)} KB CSS`,
);
