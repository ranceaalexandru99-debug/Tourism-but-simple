// Bring the web fonts into the app instead of hotlinking Google.
//
// index.html used to carry a stylesheet link to fonts.googleapis.com, which
// means every visitor's IP reaches Google on every page load — a third party
// the privacy policy does not list, alongside OpenStreetMap, Open-Meteo,
// Wikipedia, CARTO and Anthropic, which it does.
//
// Measured for a Romanian reader: 172 KB of fonts, from Google. Self-hosting is
// the same bytes from our own origin, precached by the service worker (so the
// typography survives offline), and one fewer DNS lookup and TLS handshake on
// the critical path. The old argument for hotlinking — a cache shared across
// every site using the same font — stopped being true when browsers began
// partitioning the HTTP cache per site.
//
// Re-run this to update the fonts, then commit what it writes.
//
//   node scripts/fetch-fonts.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "src", "fonts");
const OUT_CSS = path.join(ROOT, "src", "fonts.css");

const CSS_URL = "https://fonts.googleapis.com/css2"
  + "?family=Fraunces:opsz,wght@9..144,500..900"
  + "&family=Plus+Jakarta+Sans:wght@400..800"
  + "&display=swap";

// Google decides which formats to serve from the user agent; a modern one gets
// variable woff2, which is what we want.
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
  + "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

// Vietnamese is not one of the sixteen languages the app speaks, and its
// subsets are 27 KB. Everything else that is served is kept: Greek and Cyrillic
// readers get the body face, and fall back to a system serif for headings
// because Fraunces has no such subset to begin with.
const SKIP_SUBSETS = new Set(["vietnamese"]);

const css = await fetch(CSS_URL, { headers: { "User-Agent": UA } }).then((r) => {
  if (!r.ok) throw new Error(`Google answered ${r.status}`);
  return r.text();
});

// Each @font-face is preceded by a /* subset */ comment.
const parts = css.split("/*").slice(1);
fs.mkdirSync(OUT_DIR, { recursive: true });

const faces = [];
let skipped = 0;

for (const part of parts) {
  const subset = part.slice(0, part.indexOf("*/")).trim();
  const family = (part.match(/font-family:\s*['"]([^'"]+)['"]/) || [])[1];
  const url = (part.match(/src:\s*url\((https:[^)]+)\)/) || [])[1];
  const range = (part.match(/unicode-range:\s*([^;]+);/) || [])[1];
  const weight = (part.match(/font-weight:\s*([^;]+);/) || [])[1] || "400";
  const style = (part.match(/font-style:\s*([^;]+);/) || [])[1] || "normal";
  if (!family || !url) continue;
  if (SKIP_SUBSETS.has(subset)) { skipped++; continue; }

  const slug = `${family.toLowerCase().replace(/\s+/g, "-")}-${subset}.woff2`;
  const bytes = Buffer.from(await fetch(url, { headers: { "User-Agent": UA } }).then((r) => r.arrayBuffer()));
  fs.writeFileSync(path.join(OUT_DIR, slug), bytes);
  faces.push({ family, subset, slug, range, weight, style, size: bytes.length });
}

if (!faces.length) throw new Error("no @font-face blocks parsed — the CSS shape changed");

const body = faces.map((f) => `/* ${f.family} — ${f.subset} */
@font-face {
  font-family: "${f.family}";
  font-style: ${f.style};
  font-weight: ${f.weight};
  font-display: swap;
  src: url("./fonts/${f.slug}") format("woff2");
  unicode-range: ${f.range};
}`).join("\n\n");

fs.writeFileSync(OUT_CSS, `/* GENERATED by scripts/fetch-fonts.mjs — re-run it to update.

   Self-hosted on purpose: hotlinking fonts.googleapis.com sends every
   visitor's IP to a third party the privacy policy does not name, and browsers
   no longer share a font cache between sites, so it buys nothing either.

   unicode-range is kept exactly as Google generated it, so a browser still
   downloads only the subsets the page actually needs. */

${body}
`);

const total = faces.reduce((a, f) => a + f.size, 0);
console.log(`${faces.length} fonturi scrise în src/fonts/ (${(total / 1024).toFixed(0)} KB), ${skipped} subseturi sărite`);
for (const f of faces) console.log(`  ${f.slug.padEnd(38)} ${(f.size / 1024).toFixed(0).padStart(4)} KB`);
