// Real AI route generation via the Claude API.
//
// This replaces the mock POI database with a live call to Claude, so the app
// can plan ANY destination in the world (not just the 5 hardcoded cities) and
// honour free-text requests. Claude returns destination data in the exact same
// shape as the local DB entries, which we then feed through assembleRoute() —
// so the rest of the app is unchanged.
//
// The Claude call happens on the server (server/index.js), never here: this
// module only POSTs the user's preferences to /api/generate-route. The API key
// lives in ANTHROPIC_API_KEY on that server and is never part of the client
// bundle. Nothing here can leak a credential, because it holds none.
//
// With no server reachable (or one started without a key), the app falls back
// to its local engine exactly as before.

import { assembleRoute, generateRoute, resolveDestination } from "./mockEngine.js";
import { getLang } from "./i18n.js";
import { searchDestinations, nameMatchesCity } from "./destinations.js";
import { loadCityPois, buildDest } from "./poiDb.js";
import { fetchCityPoisLive } from "./osmLive.js";

// Same origin by default — dev goes through the Vite proxy (see vite.config.js),
// production behind the same host or a rewrite. Set VITE_API_BASE to point at a
// separately deployed API (e.g. "https://api.example.com").
const API_BASE = import.meta.env.VITE_API_BASE || "";

// The browser cannot know whether the server has a key until it asks. Start
// optimistic; the first definitive "ai_disabled" answer flips this off so we
// stop paying a failed round-trip on every subsequent generation.
let _aiDisabled = false;
export const hasAI = () => !_aiDisabled;

// Cache the AI-generated destination data so we don't re-call Claude for the
// same place. Keyed by destination + interests + free-text request (the things
// that change which POIs come back); days/pace/dates/budget only affect local
// assembly, so changing them reuses the cache instantly.
function cacheKey(prefs) {
  const dest = (prefs.destination || "").trim().toLowerCase();
  const ints = [...(prefs.interests || [])].sort().join(",");
  const instr = (prefs.instruction || "").trim().toLowerCase();
  return `vai_ai_dest_${dest}|${ints}|${instr}`;
}
function readCache(prefs) {
  try { const r = localStorage.getItem(cacheKey(prefs)); return r ? JSON.parse(r) : null; } catch { return null; }
}
function writeCache(prefs, dest) {
  try { localStorage.setItem(cacheKey(prefs), JSON.stringify(dest)); } catch {}
}

// Calls Claude and returns a full route (same shape as generateRoute).
export async function generateRouteAI(prefs) {
  const cached = readCache(prefs);
  if (cached) return assembleRoute(cached, prefs);

  // Abort rather than trap the user on the loading screen if the server hangs.
  // The server caps the upstream call at 45s; allow a little more for transit.
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), 50_000);
  let res;
  try {
    res = await fetch(`${API_BASE}/api/generate-route`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ prefs, lang: getLang() }),
      signal: ctrl.signal,
    });
  } finally {
    clearTimeout(timer);
  }

  if (!res.ok) {
    // A server with no key configured answers 503 ai_disabled. Remember it so
    // the tier ladder stops trying on every future generation.
    let payload = null;
    try { payload = await res.json(); } catch {}
    if (res.status === 503 && payload?.error === "ai_disabled") _aiDisabled = true;
    // 404/405 means there is no API here at all — the usual shape of a
    // static-only deployment (Netlify, GitHub Pages) with the server hosted
    // elsewhere or not yet hosted. That is structural, not transient, so stop
    // asking: otherwise every single generation waits for a doomed request and
    // then tells the user the AI failed, forever.
    if (res.status === 404 || res.status === 405) _aiDisabled = true;
    throw new Error(`Generare AI eșuată (${res.status}${payload?.error ? ` ${payload.error}` : ""})`);
  }

  const { dest: raw } = await res.json();
  if (!raw || !Array.isArray(raw.pois)) throw new Error("Răspuns AI invalid");
  // key "ai" (not "custom") so the map renders; ll present on every POI.
  const dest = { key: "ai", ...raw };

  writeCache(prefs, dest);
  return assembleRoute(dest, prefs);
}

// Tries the AI path when a key is configured; falls back to the mock engine on
// any error so the app always produces a route. The result is tagged so the UI
// can tell the user transparently when the AI call failed and we used the fast
// local engine instead:
//   _ai: true            → generated by Claude
//   _aiFailed: true      → a key is configured but the call failed (offer retry)
// (no flags when no key is configured — the mock is the intended path, no nag.)
export async function generateRouteSmart(prefs) {
  // Tier 0 — a hand-curated city in mockEngine's DB. Highest quality, and the
  // first choice — but only deep enough for about two days, so a longer trip
  // borrows the rest from the OSM tier rather than stretching nine stops over
  // a week.
  const curated = resolveDestination(prefs.destination);
  if (curated.key !== "custom") {
    try {
      const merged = await topUpCurated(curated, prefs);
      if (merged.pois.length > curated.pois.length) {
        return { ...assembleRoute(merged, prefs), _osm: true };
      }
    } catch { /* the curated route on its own is still a good route */ }
    return generateRoute(prefs);
  }

  // Tier 1 — a pre-generated OpenStreetMap POI file for this city. Real places,
  // real coords, real opening hours — no AI, no hallucination.
  try {
    const osm = await tryOsmRoute(prefs);
    if (osm) return osm;
  } catch (e) {
    console.warn("[Turism] OSM tier failed, falling through:", e);
  }

  // Tier 2 — AI generation, or the generic custom fallback when no key is set.
  if (hasAI()) {
    try {
      const route = await generateRouteAI(prefs);
      return { ...route, _ai: true };
    } catch (e) {
      console.warn("[Turism] AI generation failed, using the local engine:", e);
      return { ...generateRoute(prefs), _aiFailed: true };
    }
  }
  return generateRoute(prefs);
}

// Resolve the typed destination to an OSM-backed `dest`, or null.
// Split out from tryOsmRoute so a curated city can borrow the same data to top
// itself up — see topUpCurated below.
async function loadOsmDest(destination) {
  const head = (destination || "").split(",")[0].trim();
  if (head.length < 2) return null;
  // Try the whole head, then the first 1-2 words (the destination may carry
  // trailing modifiers like "Timișoara 2 zile").
  const words = head.split(/\s+/);
  const candidates = [head, words.slice(0, 2).join(" "), words[0]].filter((c, i, a) => c && a.indexOf(c) === i);

  let city = null;
  for (const cand of candidates) {
    const matches = await searchDestinations(cand, 1);
    const m = matches[0];
    // nameMatchesCity is alias-aware: "București"/"Londra"/"Wien" accept the
    // English-named record (Bucharest/London/Vienna) instead of falling to
    // the generic route.
    if (m && nameMatchesCity(cand, m)) { city = m; break; }
  }
  if (!city) return null;

  // Tier 1: pre-generated file. Tier 1.5: live Overpass fetch for any other
  // city in the index — real places on first request, cached locally after.
  let payload = await loadCityPois(city.id);
  if (!payload?.pois?.length) payload = await fetchCityPoisLive(city);
  if (!payload || !payload.pois?.length) return null;

  // Country ISO → name in the user's language (no per-language table).
  let country = city.c;
  try { country = new Intl.DisplayNames([getLang(), "en"], { type: "region" }).of(city.c) || city.c; } catch {}

  const dest = buildDest(
    { name: city.n, country, ll: city.ll, emoji: "📍", blurb: "" },
    payload,
  );
  // A payload can pass the ≥6-POI bar while being all cafés and restaurants —
  // buildDest then yields zero sightseeing stops, and assembleRoute would
  // happily produce an empty itinerary with a full budget attached. Fall
  // through to the next tier instead of shipping an empty trip.
  if (dest.pois.length < 3) return null;
  return dest;
}

async function tryOsmRoute(prefs) {
  const dest = await loadOsmDest(prefs.destination);
  if (!dest) return null;
  return { ...assembleRoute(dest, prefs), _osm: true };
}

// How many stops a trip of this length actually wants.
const stopsWanted = (prefs) => {
  const perDay = prefs.pace === "relaxed" ? 3 : prefs.pace === "packed" ? 5 : 4;
  const days = prefs.days === "flex" ? 3 : Math.max(1, Math.min(7, prefs.days || 1));
  return days * perDay;
};

// Curated cities carry 7–11 hand-written stops: about two full days. Ask one of
// them for a week and you used to get seven stops spread across seven days —
// one a day — because Tier 0 answered and the ladder stopped there. The very
// cities with the best-written entries gave the thinnest long trips.
//
// So keep the curated stops, which have real tips and are properly ordered, and
// top up from OpenStreetMap only when the trip is longer than they can fill.
async function topUpCurated(dest, prefs) {
  const wanted = stopsWanted(prefs);
  if (dest.pois.length >= wanted) return dest;

  const osm = await loadOsmDest(prefs.destination);
  if (!osm?.pois?.length) return dest;

  const seen = new Set(dest.pois.map((p) => (p.name || "").trim().toLowerCase()));
  const extra = osm.pois.filter((p) => !seen.has((p.name || "").trim().toLowerCase()));
  if (!extra.length) return dest;

  return {
    ...dest,
    pois: [...dest.pois, ...extra.slice(0, wanted - dest.pois.length)],
    // The curated food list is short and hand-picked; OSM's is longer. Use
    // whichever actually has entries, preferring the curated one.
    food: dest.food?.length ? dest.food : osm.food,
  };
}
